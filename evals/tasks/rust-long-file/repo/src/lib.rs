/// Base price in cents for a parcel to Europe weighing `grams`, by weight tier.
fn tier_price_europe(grams: u32) -> Option<u32> {
    if grams <= 250 {
        Some(450)
    } else if grams <= 500 {
        Some(570)
    } else if grams <= 1000 {
        Some(690)
    } else if grams <= 2000 {
        Some(810)
    } else if grams <= 3000 {
        Some(930)
    } else if grams <= 5000 {
        Some(1050)
    } else if grams <= 7500 {
        Some(1170)
    } else if grams <= 10000 {
        Some(1290)
    } else if grams <= 15000 {
        Some(1410)
    } else if grams <= 20000 {
        Some(1530)
    } else if grams <= 25000 {
        Some(1650)
    } else if grams <= 30000 {
        Some(1770)
    } else {
        None
    }
}

