fn is_remote(postcode: &str) -> bool {
    REMOTE_PREFIXES.iter().any(|p| postcode.starts_with(p))
}

/// Heavy parcels (over 10 kg) pay a handling fee per started 5 kg above 10 kg.
fn heavy_fee(grams: u32) -> u32 {
    if grams <= 10_000 {
        return 0;
    }
    let extra = grams - 10_000;
    let blocks = extra / 5_000;
    blocks * 350
}

/// Rounds cents up to the next 5 cents.
fn round_up_5(cents: u32) -> u32 {
    cents.div_ceil(5) * 5
}

#[derive(Debug, PartialEq, Eq)]
pub struct Quote {
    pub zone: Zone,
    pub cents: u32,
}

/// Quotes a parcel: tier price, plus heavy fee and remote fee, plus fuel surcharge on the
/// total, rounded up to 5 cents. `None` for unknown countries or parcels over 30 kg.
pub fn quote(country: &str, postcode: &str, grams: u32, month: u32) -> Option<Quote> {
    let zone = zone_for(country)?;
    let tier = match zone {
        Zone::Europe => tier_price_europe(grams)?,
        Zone::Americas => tier_price_americas(grams)?,
        Zone::Asia => tier_price_asia(grams)?,
        Zone::Africa => tier_price_africa(grams)?,
        Zone::MiddleEast => tier_price_middleeast(grams)?,
        Zone::Oceania => tier_price_oceania(grams)?,
    };
    let remote = if is_remote(postcode) { 400 } else { 0 };
    let subtotal = tier + heavy_fee(grams) + remote;
    let fuel = subtotal * fuel_surcharge_bps(zone, month) / 10_000;
    Some(Quote { zone, cents: round_up_5(subtotal + fuel) })
}

